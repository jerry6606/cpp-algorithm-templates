/*
题目：区间求和（一维前缀和）
描述：给定一个静态数组（下标从 1 开始），接下来有多次询问。每次询问给出 l 与 r，请输出数组中第 l 个到第 r 个元素的和，包括两端。数组在所有询问期间不发生修改。
输入格式：
第一行包含整数 n 与 q，用空格分隔，n 表示数组长度，q 表示询问次数。
第二行包含 n 个整数，表示数组 a[1] 到 a[n]。
接下来 q 行，每行包含整数 l 与 r，用空格分隔，表示一次询问，保证 1 <= l <= r <= n。
输出格式：
对每次询问输出一行，包含一个整数，表示区间 [l, r] 内所有元素的和。每行输出一个答案。
样例输入 1：
5 3
1 2 3 4 5
1 3
2 5
5 5
样例输出 1：
6
14
5
样例输入 2：
4 2
-2 5 -1 3
1 4
2 3
样例输出 2：
5
4
约束与提示：
- 数组元素可以为负数，区间和可能较大，程序中使用 long long 存储。
- 预处理一次后每次询问可在 O(1) 时间内回答；如果数组会被修改，本方法不再适用。
*/
// 一维前缀和：静态数组多次区间求和
// s[i] = 前 i 个数之和（s[0] = 0 哨兵）；区间 [l, r] 和 = s[r] - s[l-1]
// 复杂度：预处理 O(n)，每次查询 O(1)
// 易错点：下标从 1 起，数组开 n+1 格；和用 long long；数组会改就不能用这个
// 验证：2026-10-01 练习 1 一次 100 分（样例/单格/负数/大数全过）
#include <bits/stdc++.h>
using namespace std;
int main() {
    int n, q;
    if (!(cin >> n >> q)) return 0;
    vector<long long> s(n + 1, 0);
    for (int i = 1; i <= n; i++) {
        long long x;
        cin >> x;
        s[i] = s[i - 1] + x;
    }
    while (q--) {
        int l, r;
        cin >> l >> r;
        cout << s[r] - s[l - 1] << '\n';
    }
    return 0;
}
