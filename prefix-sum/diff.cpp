/*
题目：区间加（一维差分）
描述：给定一个初始数组（下标从 1 开始），接下来依次进行多次区间加操作。每次操作给出 l、r 与 v，表示把数组中第 l 个到第 r 个元素每个都加上 v，包括两端。所有操作全部完成后，输出最终的整个数组。本题没有边修改边询问的情况。
输入格式：
第一行包含整数 n 与 q，用空格分隔，n 表示数组长度，q 表示操作次数。
第二行包含 n 个整数，表示初始数组 a[1] 到 a[n]。
接下来 q 行，每行包含整数 l、r 与 v，用空格分隔，表示一次区间加操作，保证 1 <= l <= r <= n，v 可以为负数。
输出格式：
输出一行，包含 n 个整数，用空格分隔，表示全部操作完成后的数组。行末可以有空格。
样例输入 1：
5 2
1 2 3 4 5
1 3 10
4 5 -1
样例输出 1：
11 12 13 3 4
样例输入 2：
4 1
0 0 0 0
2 3 7
样例输出 2：
0 7 7 0
约束与提示：
- v 与操作后的元素值可能较大，程序中统一使用 long long 存储。
- 本方法只适合全部修改完成后再统一输出的情形；如果需要边修改边询问每个位置的值，需要使用其他数据结构。
*/
// 一维差分：多次区间加，最后输出整个数组
// d[i] = a[i] - a[i-1]；区间 [l, r] 加 v：d[l] += v，d[r+1] -= v；最后对 d 做前缀和还原
// 复杂度：每次修改 O(1)，还原 O(n)
// 易错点：d 开 n+2 格（r+1 最大到 n+1）；值与增量整条用 long long，别中间掉成 int；
//   只适合"改完再输出"，边改边查要用树状数组/线段树
// 验证：2026-10-04 练习 100 分（大数 4e9 压测过）
#include <bits/stdc++.h>
using namespace std;
int main() {
    int n, q;
    if (!(cin >> n >> q)) return 0;
    vector<long long> a(n + 1, 0), d(n + 2, 0);
    for (int i = 1; i <= n; i++) {
        cin >> a[i];
        d[i] = a[i] - a[i - 1];
    }
    while (q--) {
        int l, r;
        long long v;
        cin >> l >> r >> v;
        d[l] += v;
        d[r + 1] -= v;
    }
    long long cur = 0;
    for (int i = 1; i <= n; i++) {
        cur += d[i];
        cout << cur << ' ';
    }
    cout << '\n';
    return 0;
}
