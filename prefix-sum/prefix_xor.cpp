/*
题目：区间异或（一维前缀异或）
描述：给定一个静态数组（下标从 1 开始），接下来有多次询问。每次询问给出 l 与 r，请输出数组中第 l 个到第 r 个元素逐个异或的结果，包括两端。数组在所有询问期间不发生修改。
输入格式：
第一行包含整数 n 与 q，用空格分隔，n 表示数组长度，q 表示询问次数。
第二行包含 n 个整数，表示数组 a[1] 到 a[n]。
接下来 q 行，每行包含整数 l 与 r，用空格分隔，表示一次询问，保证 1 <= l <= r <= n。
输出格式：
对每次询问输出一行，包含一个整数，表示区间 [l, r] 内所有元素的异或结果。每行输出一个答案。
样例输入 1：
4 2
5 3 7 2
1 4
2 3
样例输出 1：
3
4
样例输入 2：
3 2
7 7 7
1 2
1 3
样例输出 2：
0
7
约束与提示：
- 异或运算满足相同数值异或两次会抵消的规律，因此区间异或可以用两个前缀异或值异或得到。
- 预处理一次后每次询问可在 O(1) 时间内回答。
*/
// 一维前缀异或：静态数组多次区间异或
// s[i] = a[1]^a[2]^...^a[i]；区间 [l, r] 异或 = s[r] ^ s[l-1]（异或的逆运算是它自己）
// 复杂度：预处理 O(n)，每次查询 O(1)
// 易错点：构造和查询的运算符必须配套（都用 ^，不能一个 ^ 一个 -）；数组开 n+1 格
// 验证：2026-10-02 重做 100 分（含 l>1 区间）
#include <bits/stdc++.h>
using namespace std;
int main() {
    int n, q;
    if (!(cin >> n >> q)) return 0;
    vector<int> s(n + 1, 0);
    for (int i = 1; i <= n; i++) {
        int a;
        cin >> a;
        s[i] = s[i - 1] ^ a;
    }
    while (q--) {
        int l, r;
        cin >> l >> r;
        cout << (s[r] ^ s[l - 1]) << '\n';
    }
    return 0;
}
