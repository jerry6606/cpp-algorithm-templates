/*
题目：子矩阵求和（二维前缀和）
描述：给定一个静态矩阵（行与列下标均从 1 开始），接下来有多次询问。每次询问给出左上角 (x1, y1) 与右下角 (x2, y2)，请输出该子矩阵内所有元素的和，包括边界。矩阵在所有询问期间不发生修改。
输入格式：
第一行包含整数 n、m 与 q，用空格分隔，n 表示行数，m 表示列数，q 表示询问次数。
接下来 n 行，每行包含 m 个整数，表示矩阵的一行。
接下来 q 行，每行包含整数 x1、y1、x2、y2，用空格分隔，表示一次询问，保证 1 <= x1 <= x2 <= n 且 1 <= y1 <= y2 <= m。
输出格式：
对每次询问输出一行，包含一个整数，表示对应子矩阵内所有元素的和。每行输出一个答案。
样例输入 1：
3 3 2
1 2 3
4 5 6
7 8 9
1 1 2 2
2 2 3 3
样例输出 1：
12
28
样例输入 2：
2 3 1
1 0 2
-1 3 4
1 1 2 3
样例输出 2：
9
约束与提示：
- 矩阵元素可以为负数，子矩阵和可能较大，程序中使用 long long 存储。
- 预处理一次后每次询问可在 O(1) 时间内回答。
*/
// 二维前缀和：静态矩阵多次子矩阵求和
// s[i][j] = (1,1)->(i,j) 子矩阵和
// 递推：s[i][j] = a[i][j] + s[i-1][j] + s[i][j-1] - s[i-1][j-1]
// 查询 (x1,y1)->(x2,y2)：s[x2][y2] - s[x1-1][y2] - s[x2][y1-1] + s[x1-1][y1-1]
//   （容斥：大矩形减上条、减左条，左上角被减两次补一次）
// 复杂度：预处理 O(nm)，每次查询 O(1)
// 易错点：数组开 (n+1)x(m+1) 格，第 0 行/列哨兵；和用 long long
// 验证：2026-10-02 练习 100 分；2026-10-04 重做 100 分
#include <bits/stdc++.h>
using namespace std;
int main() {
    int n, m, q;
    if (!(cin >> n >> m >> q)) return 0;
    vector<vector<long long>> s(n + 1, vector<long long>(m + 1, 0));
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= m; j++) {
            long long a;
            cin >> a;
            s[i][j] = a + s[i - 1][j] + s[i][j - 1] - s[i - 1][j - 1];
        }
    }
    while (q--) {
        int x1, y1, x2, y2;
        cin >> x1 >> y1 >> x2 >> y2;
        cout << s[x2][y2] - s[x1 - 1][y2] - s[x2][y1 - 1] + s[x1 - 1][y1 - 1] << '\n';
    }
    return 0;
}
