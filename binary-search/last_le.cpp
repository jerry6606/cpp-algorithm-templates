/*
题目：查找最后一个小于等于 x 的位置
描述：给定一个升序数组，查找最后一个小于等于给定值 x 的元素，输出它的下标（下标从 0 开始）。如果数组中所有元素都大于 x，则输出 -1。
输入格式：
第一行包含整数 n 与整数 x，用空格分隔，n 表示数组长度，x 表示目标值。
第二行包含 n 个整数，表示升序数组 a[0] 到 a[n-1]。
输出格式：
输出一个整数，表示最后一个小于等于 x 的元素的下标；不存在时输出 -1。
样例输入 1：
5 3
1 2 3 3 5
样例输出 1：
3
样例输入 2：
5 0
1 2 3 3 5
样例输出 2：
-1
约束与提示：
- 数组已按升序给出，存在重复元素时返回最右侧的位置。
- 元素与 x 的取值在 long long 范围内，程序中使用 long long 存储。
- 要求用二分查找完成，时间复杂度为 O(log n)。
*/
// 最后一个 <= x 的位置（升序数组，下标 0 起），不存在返回 -1
// 场景：右边界查找
// 复杂度：O(log n)
// 易错点：比较式 = mid 处的值 vs 目标 x（右边写成 mid 就是错）；ans 先初始化 -1
// 验证：2026-09-30 Day3 重练一次通过
#include <bits/stdc++.h>
using namespace std;
int main() {
    int n;
    long long x;
    if (!(cin >> n >> x)) return 0;
    vector<long long> a(n);
    for (int i = 0; i < n; i++) cin >> a[i];
    int l = 0, r = n - 1, ans = -1;
    while (l <= r) {
        int mid = l + (r - l) / 2;
        if (a[mid] <= x) {   // 命中先记下，再往右收
            ans = mid;
            l = mid + 1;
        } else {
            r = mid - 1;
        }
    }
    cout << ans << '\n';
    return 0;
}
